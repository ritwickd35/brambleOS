#!/usr/bin/env python3
"""Generate ui/src/font_data.h: anti-aliased proportional fonts (ASCII 32..126), 2 bits per pixel, sizes 7, 9, 12, 16, 24.
Per size: glyph table {u8 w, h; s8 xoff, yoff; u8 adv; u16 off} + packed bitmap (rows of w px, 4 px per byte, MSB first)."""
import os, sys
import numpy as np
from PIL import Image, ImageDraw, ImageFont
SIZES = (7, 8, 9, 12, 16, 24); OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "ui", "src", "font_data.h")
o = ["/* generated by tools/ui_font.py - do not edit */", "typedef struct { unsigned char w, h; signed char xo, yo; unsigned char adv; unsigned short off; } glyph_t;",
     "typedef struct { unsigned char height, ascent; const glyph_t *g; const unsigned char *bits; } font_t;"]
total = 0; ext = []
# San Francisco (Apple system font) by default. Apple's licence does not allow redistributing it, so the generated
# font_data.h is git-ignored; set UI_FONT to a free font (e.g. Inter) for anything published.
FONT = os.environ.get("UI_FONT", "/System/Library/Fonts/SFNS.ttf")
TRACK = int(os.environ.get("UI_TRACK", "1"))                   # extra pixels between letters (small sizes smear together)
WGHT = os.environ.get("UI_WGHT")                               # weight for variable fonts, e.g. 600
def load(sz):
    # per-size override: UI_FONT16 / UI_WGHT16 / UI_TRACK16 (the preset name uses size 16)
    fn = os.environ.get(f"UI_FONT{sz}", FONT); wg = os.environ.get(f"UI_WGHT{sz}", WGHT)
    if not os.path.exists(fn): return ImageFont.load_default(size=sz)
    f = ImageFont.truetype(fn, sz)
    if wg:
        try: f.set_variation_by_axes([float(wg) if a.get("name", b"") in (b"Weight", "Weight") else a["default"] for a in f.get_variation_axes()])
        except Exception: pass
    return f
for sz in SIZES:
    f = load(sz); asc, desc = f.getmetrics(); gl = []; bits = bytearray()
    for c in range(32, 127):
        ch = chr(c); adv = int(round(f.getlength(ch))) + (int(os.environ.get(f'UI_TRACK{sz}', TRACK)) if ch != ' ' else 0); im = Image.new("L", (sz * 2, sz * 2), 0); ImageDraw.Draw(im).text((sz // 2, 0), ch, font=f, fill=255)
        a = np.asarray(im, float) / 255; ys, xs = np.nonzero(a > 0.12)
        if len(xs) == 0: gl.append((0, 0, 0, 0, max(adv, sz // 3), len(bits))); continue
        x0, x1, y0, y1 = xs.min(), xs.max() + 1, ys.min(), ys.max() + 1; w, h = x1 - x0, y1 - y0
        q = np.clip(np.round(a[y0:y1, x0:x1] * 3), 0, 3).astype(int); off = len(bits)
        flat = q.reshape(-1); flat = np.r_[flat, np.zeros((-len(flat)) % 4, int)]
        for i in range(0, len(flat), 4): bits.append((flat[i] << 6) | (flat[i + 1] << 4) | (flat[i + 2] << 2) | flat[i + 3])
        gl.append((w, h, x0 - sz // 2, y0, adv, off))
    ext.append(f"extern const font_t FONT{sz};")
    o.append(f"static const glyph_t G{sz}[95] = {{" + ",".join("{%d,%d,%d,%d,%d,%d}" % g for g in gl) + "};")
    o.append(f"static const unsigned char B{sz}[{len(bits)}] = {{" + ",".join(str(b) for b in bits) + "};")
    o.append(f"const font_t FONT{sz} = {{{asc + desc}, {asc}, G{sz}, B{sz}}};"); total += len(bits) + 95 * 7
# one copy of the data: the header declares the fonts; the definitions are compiled only where FONT_DATA_IMPL is set (gfx.c)
open(OUT, "w").write("\n".join(o[:3] + ext + ["#ifdef FONT_DATA_IMPL"] + o[3:] + ["#endif"]) + "\n"); print("font_data.h:", total, "bytes of data")
