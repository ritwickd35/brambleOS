#!/usr/bin/env python3
"""Generate the engine instruction probe table (cut1/eprobe_tests.h) and plan (logs/eprobe_plan.json).
Each run: set r0..r14 from a config, execute the test words, (control tests) 18 counter markers, store r0..r14 + done.
Layout: program at code 0xE00: 4-word re-entry guard, setup 30 words, test words at 0xE22."""
import json, os, struct
RE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
f2u = lambda f: struct.unpack("<I", struct.pack("<f", f))[0]
P = [[int(x, 16) for x in l.split()] for l in open(os.path.join(RE, "cfw", "engine_progs.txt")).read().strip().split("\n")]
UNK = [int(l.split()[0], 16) for l in open(os.path.join(RE, "logs", "unk_words.txt"))]
BASE, TW, NMARK = 0xE00, 0xE00 + 34, 18

import numpy as np
F = np.float32
def _cfg(c, k):          # must match cfgval() in cut1/combo4.c (float32 arithmetic)
    sg = F(-1) if k & 1 else F(1)
    v = [F(0.25) + F(0.5) * F(k), sg * (F(2.0) - F(0.13) * F(k)), F(0.6), F(0.03) * F(k + 1) * (-sg),
         None, F(0), F(k + 1) * F(300.0) * sg, None][c]
    if c == 4: return 0xC80 + k
    if c == 7: return 1
    return f2u(float(v))
CFG = [[_cfg(c, k) for k in range(15)] for c in range(8)]


def regs_of(w):
    return {(w >> 24) & 15, (w >> 20) & 15, w & 15}


def ctr_for(words):
    used = set().union(*[regs_of(w) for w in words]) if words else set()
    for c in (13, 12, 11, 10, 9, 8, 7):
        if c not in used: return c
    raise ValueError


tests = []                    # (name, words, ctr or 255)
def add(name, words, ctl=False): tests.append((name, list(words), ctr_for(words) if ctl else 255))

add("baseline empty", [])
add("baseline add r0,#0", [0x70000000])
for w in [0x85460003, 0x873a000b, 0xc12e0001, 0xcb8f000b, 0xf6540000, 0x7d000006, 0x72c63f80, 0x72863000]:
    add(f"known {w:08x}", [w])
add("known e2130000 ld++", [0xe2130000])
for w in UNK:
    c = w >> 28
    if c in (9, 0xa) or (w >> 24) == 0x20: continue
    add(f"unk {w:08x}", [w])
# conditional words alone and with the stock preceding word
seen = set()
for w in UNK:
    if w >> 28 != 9: continue
    add(f"cond {w:08x}", [w], True)
    for p in P:
        for i, x in enumerate(p):
            if x == w and i and (p[i - 1], w) not in seen and (p[i - 1] >> 28) not in (9, 0xa):
                seen.add((p[i - 1], w)); add(f"pair {p[i-1]:08x} {w:08x}", [p[i - 1], w], True)
# calls / returns with link register R: target = 3 markers ahead
for w in UNK:
    if w >> 28 != 0xA: continue
    R, b1, fl = (w >> 24) & 15, (w >> 16) & 255, w & 0xF000
    if b1 == 0x06:
        add(f"call {w:08x}", [(w & 0xFFFFF000) | (TW + 1 + 3)], True)
    elif b1 == 0x0A:
        add(f"ret {w:08x}", [0x70060000 | (R << 24) | (TW + 2 + 3), w], True)
add("ret ae0a4000", [0x7e060000 | (TW + 2 + 3), 0xae0a4000], True)
add("call ae064xxx", [0xae064000 | (TW + 1 + 3)], True)
# vector op 20030000 with r8 scalar/addr, r9 src, r10 n, r11 dst
add("vec 20030000 (r8=0xC90)", [0x78060C90, 0x79060C80, 0x7a060004, 0x7b060C88, 0x20030000])
add("vec 20030000 (r8=2.0)", [0x78c64000, 0x78860000, 0x79060C80, 0x7a060004, 0x7b060C88, 0x20030000])
for w in (0x20000000, 0x20070000, 0x20080000, 0x200d0000):
    add(f"vec {w:08x}", [0x78060C90, 0x79060C80, 0x7a060004, 0x7b060C88, w])
for name, words, ctr in tests:
    assert len(words) <= 6, name
import sys
ROUND = int(sys.argv[1]) if len(sys.argv) > 1 else 1
if ROUND == 2:      # round 2: what round 1 did not reach, minus the 9-class S=6 words (they stopped the engine)
    HAZ = {0x934601f5, 0x9d0601d0, 0x9d0601db}
    tests = tests[:2] + [t for t in tests[109:] if not HAZ & set(t[1])]
    for w in (0xc57f0008, 0xc01f0003, 0xc39f0009, 0xc12e0001, 0xc67e0008):
        add(f"order {w:08x}", [w])
    add("r15 plain", [0x5f080C8F])
    for w in (0xc23f0005, 0xc12e0001, 0x85460003, 0x70020002, 0xc0220003):
        add(f"r15 after {w:08x}", [w, 0x5f080C8F])
    for w in (0x9f0a3c01, 0x9f083c01):
        for pre in (0xc23f0005, 0xc12e0001, 0xc0220003):
            add(f"r15cond {pre:08x} {w:08x}", [pre, w], True)

flat, idx = [], []
for name, words, ctr in tests:
    idx.append((len(flat), len(words), ctr)); flat += words
h = ["/* generated by tools/eprobe_gen.py */",
     f"#define NTEST {len(tests)}", f"#define NCFG {len(CFG)}", f"#define TW {TW}", f"#define NMARK {NMARK}",
     "static const uint32_t T_WORDS[] = {" + ",".join(f"0x{w:08x}u" for w in flat) + "};",
     
     "static const uint8_t T_LEN[] = {" + ",".join(str(n) for _, n, _ in idx) + "};",
     "static const uint8_t T_CTR[] = {" + ",".join(str(c) for _, _, c in idx) + "};"]
open(os.path.join(RE, "cut1", "eprobe_tests.h"), "w").write("\n".join(h) + "\n")
json.dump(dict(tests=[dict(name=n, words=w, ctr=c) for n, w, c in tests], cfg=CFG, base=BASE, tw=TW, nmark=NMARK),
          open(os.path.join(RE, "logs", "eprobe_plan.json" if ROUND == 1 else f"eprobe_plan{ROUND}.json"), "w"), indent=0)
print("tests", len(tests), "runs", len(tests) * len(CFG), "words", len(flat))
