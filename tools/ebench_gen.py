#!/usr/bin/env python3
"""Engine cost benchmarks (cut 8c): programs for the EQ slot, assembled with easm; header cut1/ebench_progs.h."""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); RE = os.path.dirname(HERE); sys.path.insert(0, HERE)
from easm import assemble
GUARD = "ld r1,[0xC3E]\ndjnz r1, go\nhalt\ngo: st [0xC3E], r1\n"
def loop(n, body, setup=""):
    return GUARD + setup + f"mov r4,#{n}\nL: " + body + "\ndjnz r4, L\nhalt\n"
rep = lambda s, k: "\n".join([s] * k)
B = [("empty", GUARD + "halt\n"),
     ("loop only x400", loop(400, "add r5,#1")),
     ("fadd x8 x200", loop(200, rep("fadd r1,r1,r2", 8))),
     ("fmac x8 x200", loop(200, rep("fmac r1,r2,r3", 8))),
     ("fmul x8 x200", loop(200, rep("fmul r1,r2,r3", 8))),
     ("ld direct x8 x200", loop(200, rep("ld r2,[0xC00]", 8))),
     ("st direct x8 x200", loop(200, rep("st [0xC00],r2", 8))),
     ("ld indexed x8 x200", loop(200, rep("ld r2,[r6]", 8), "mov r6,#0xC00\n")),
     ("ldc x8 x200", loop(200, rep("ldc r2,[r6]", 8), "mov r6,#0xE00\n")),
     ("iadd x8 x200", loop(200, rep("iadd r1,r1,r2", 8))),
     ("skip not taken x8 x200", loop(200, "\n".join(f"skipbs r5,0,S{i}\nS{i}:" for i in range(8)) + " add r6,#0", "mov r5,#0\n")),
     ("rsqrt x8 x100", loop(100, rep("rsqrt r2,r3", 8), "movf r3,2.0\n")),
     ("dot16 x200", loop(200, "mov r8,#0xC00\nmov r9,#0xC40\nmov r10,#16\nvdot", )),
     ("dot64 x100", loop(100, "mov r8,#0xC00\nmov r9,#0xC40\nmov r10,#64\nvdot")),
     ("copy64 x100", loop(100, "mov r9,#0xC00\nmov r10,#64\nmov r11,#0xC40\nvcopy")),
     ("scale64 x100", loop(100, "mov r9,#0xC00\nmov r10,#64\nmov r11,#0xC40\nvmuls", "movf r8,0.5\n")),
     ("mov x8 x200", loop(200, rep("mov r2,r3", 8))),
     ("andh x8 x200", loop(200, rep("andh r2,#0x7fff", 8)))]
import easm; easm.VEC["vdot"] = 0xD
flat, idx = [], []
for name, src in B:
    w, _ = assemble(src, 0xE00); assert len(w) < 480, name
    idx.append((len(flat), len(w))); flat += w
h = ["/* generated by tools/ebench_gen.py */", f"#define NB {len(B)}",
     "static const uint32_t B_WORDS[] = {" + ",".join(f"0x{x:08x}u" for x in flat) + "};",
     "static const uint16_t B_OFF[] = {" + ",".join(str(o) for o, _ in idx) + "};",
     "static const uint16_t B_LEN[] = {" + ",".join(str(n) for _, n in idx) + "};"]
open(os.path.join(RE, "cut1", "ebench_progs.h"), "w").write("\n".join(h) + "\n")
json.dump([n for n, _ in B], open(os.path.join(RE, "logs", "ebench_plan.json"), "w"))
print("benches", len(B), "words", len(flat))
