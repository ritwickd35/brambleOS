#!/usr/bin/env python3
"""Design of the polyphase IIR half-band filter used for 2x oversampling (two parallel chains of first-order
all-pass sections in z^-2; algorithm of Valenzuela & Constantinides as implemented in L. de Soras' HIIR).
Writes dsp/hb_coefs.h and prints the measured stop-band attenuation."""
import math, os, sys
import numpy as np


def _acc_num(q, order, c):
    i, j, acc = 0, 1, 0.0
    while True:
        t = q ** (i * (i + 1)) * math.sin((i * 2 + 1) * c * math.pi / order) * j
        acc += t; j = -j; i += 1
        if abs(t) <= 1e-100: return acc


def _acc_den(q, order, c):
    i, j, acc = 1, -1, 0.0
    while True:
        t = q ** (i * i) * math.cos(i * 2 * c * math.pi / order) * j
        acc += t; j = -j; i += 1
        if abs(t) <= 1e-100: return acc


def design(ncoef, tbw):
    k = math.tan((1 - 2 * tbw) * math.pi / 4) ** 2
    kk = (1 - k * k) ** 0.25
    e = 0.5 * (1 - kk) / (1 + kk); e4 = e ** 4
    q = e * (1 + e4 * (2 + e4 * (15 + 150 * e4)))
    order = ncoef * 2 + 1; out = []
    for idx in range(ncoef):
        c = idx + 1
        ww = _acc_num(q, order, c) * q ** 0.25 / (_acc_den(q, order, c) + 0.5)
        w2 = ww * ww
        x = math.sqrt((1 - w2 * k) * (1 - w2 / k)) / (1 + w2)
        out.append((1 - x) / (1 + x))
    return out


def response(coefs, n=8192):
    """Half-band low-pass H(z) = 0.5*(A0(z^2) + z^-1 A1(z^2)); A = prod (c + z^-2)/(1 + c z^-2)."""
    w = np.linspace(0, np.pi, n); z2 = np.exp(-2j * w)
    a0 = np.ones(n, complex); a1 = np.ones(n, complex)
    for i, c in enumerate(coefs):
        s = (c + z2) / (1 + c * z2)
        if i % 2 == 0: a0 *= s
        else: a1 *= s
    h = 0.5 * (a0 + np.exp(-1j * w) * a1)
    return w / np.pi, 20 * np.log10(np.abs(h) + 1e-15)


if __name__ == "__main__":
    ncoef, tbw = int(sys.argv[1]) if len(sys.argv) > 1 else 8, float(sys.argv[2]) if len(sys.argv) > 2 else 0.05
    c = design(ncoef, tbw)
    f, m = response(c)
    stop = m[f > 0.5 + tbw].max(); pas = m[f < 0.5 - tbw].min()
    print(f"{ncoef} coefficients, transition {tbw}: stop-band {stop:.1f} dB, pass-band ripple {pas:.4f} dB")
    print("at 2x of 44.1 kHz: pass band to", round((0.5 - tbw) * 44100), "Hz, stop band from", round((0.5 + tbw) * 44100), "Hz")
    h = os.path.join(os.path.dirname(os.path.abspath(__file__)), "hb_coefs.h")
    with open(h, "w") as fh:
        fh.write(f"/* generated by hb_design.py: {ncoef} coefs, tbw {tbw}, stop band {stop:.1f} dB */\n")
        fh.write(f"#define HB_N {ncoef}\nstatic const float hb_c[HB_N] = {{" + ", ".join(f"{x:.9f}f" for x in c) + "};\n")
    print("wrote", h)
